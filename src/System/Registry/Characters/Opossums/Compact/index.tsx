/**
 * Compact Steed Rider Height Calibration Algorithm
 * Mathematical standard: Supports riders up to a maximum height of 4 feet and 4.44 inches.
 * 4 feet * 12 inches/ft + 4.44 inches = 52.44 inches maximum rider height.
 * Calibrated specifically for Sean White (3'3" = 39") and George Blake (4'4" = 52").
 */
export const COMPACT_RIDER_HEIGHT_LIMITS = {
  maxFeet: 4,
  maxInches: 4.44,
  maxTotalInches: 52.44,
  formatted: "4 feet and 4.44 inches",
  badgeFormatted: "4'4.44\"",
  isRiderEligible: (riderHeightInches: number): boolean => {
    return riderHeightInches <= 52.44;
  },
  parseRiderHeightInches: (heightStr?: string): number => {
    if (!heightStr) return 0;
    const feetMatch = heightStr.match(/(\d+(?:\.\d+)?)\s*(?:feet|ft|')/i);
    const inchesMatch = heightStr.match(/(\d+(?:\.\d+)?)\s*(?:inches|in|")/i);
    const feet = feetMatch ? parseFloat(feetMatch[1]) : 0;
    const inches = inchesMatch ? parseFloat(inchesMatch[1]) : 0;
    return feet * 12 + inches;
  }
};

